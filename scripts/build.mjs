#!/usr/bin/env node
/**
 * Zero-dependency bundler for the Client half.
 *
 * The Harness Web loader expects one browser module per plugin, registered as
 * `window.__ModuleLoader__.load({ id, factory })`. To keep the source readable
 * without pulling a bundler into the repository, `src/**` is written as plain
 * ES modules that Node can import and test directly; this script strips their
 * `import`/`export` keywords in a fixed order and wraps the result in that
 * loader call.
 *
 * Rules the sources must follow (asserted below):
 * - every `import` is a single-line statement,
 * - every `export` is a leading keyword on a declaration,
 * - no two modules declare the same top-level name (the file is one scope).
 */

import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

/** Concatenation order: data → state → presentation → registration. */
const MODULES = [
  'src/lib/i18n.js',
  'src/lib/links.js',
  'src/lib/wmo.js',
  'src/lib/format.js',
  'src/lib/cache.js',
  'src/lib/alert-guides.js',
  'src/lib/alerts.js',
  'src/lib/typhoon.js',
  'src/lib/districts-data.js',
  'src/lib/districts.js',
  'src/lib/geo.js',
  'src/lib/weather.js',
  'src/lib/history.js',
  'src/lib/procharts.js',
  'src/lib/satellite.js',
  'src/lib/radar.js',
  'src/lib/notice-core.js',
  'src/lib/store.js',
  'src/ui/styles.js',
  'src/ui/icons.js',
  'src/ui/chart.js',
  'src/ui/basemap-data.js',
  'src/ui/typhoon-view.js',
  'src/ui/media-zoom.js',
  'src/ui/history-chart.js',
  'src/ui/alerts-view.js',
  'src/ui/satellite-view.js',
  'src/ui/pro-chart-view.js',
  'src/ui/radar-view.js',
  'src/ui/notice.js',
  'src/ui/panel.js',
  'src/plugin.js'
];

const IMPORT_LINE = /^\s*import\s/;
const EXPORT_DECLARATION = /^export\s+(?=(?:async\s+function|function|class|const|let|var)\b)/;

function stripModuleSyntax(source, file) {
  const output = [];
  const lines = source.split(/\r?\n/);
  lines.forEach((line, index) => {
    if (IMPORT_LINE.test(line)) {
      if (!/;\s*$/.test(line)) {
        throw new Error(`${file}:${index + 1}: imports must be single-line statements`);
      }
      return;
    }
    output.push(line.replace(EXPORT_DECLARATION, ''));
  });
  const transformed = output.join('\n');
  if (/^\s*(?:import|export)\s/m.test(transformed)) {
    throw new Error(`${file}: module syntax left after transform`);
  }
  return transformed.trimEnd();
}

function indent(block) {
  return block.split('\n').map(line => (line.length > 0 ? `    ${line}` : line)).join('\n');
}

const chunks = MODULES.map(modulePath => {
  const absolute = join(ROOT, modulePath);
  statSync(absolute);
  const source = readFileSync(absolute, 'utf8');
  return `    /* ---- ${relative(ROOT, absolute).split('\\').join('/')} ---- */\n${indent(stripModuleSyntax(source, modulePath))}`;
});

const banner = `/*!
 * ${pkg.name} ${pkg.version} — browser bundle
 * Generated by scripts/build.mjs from src/. Do not edit this file by hand.
 * Locating, fetching, caching and rendering all run in this module; the Host
 * half (index.js) only exists so the bundle row resolves.
 */`;

const bundle = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    const React = require('react');
    const h = React.createElement;

${chunks.join('\n\n')}

    return { inject: ['slots', 'locale'], apply };
  }
});
`;

const target = join(ROOT, 'client.js');
writeFileSync(target, bundle, 'utf8');
const bytes = Buffer.byteLength(bundle, 'utf8');
console.log(`built client.js — ${MODULES.length} modules, ${(bytes / 1024).toFixed(1)} KiB`);
